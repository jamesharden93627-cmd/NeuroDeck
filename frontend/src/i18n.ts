/** 功能：只接受受支持语言，避免浏览器区域码或损坏的缓存值影响初始化。 */
function resolveInitialLanguage(): AppLanguage {
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (stored === "zh" || stored === "en") return stored;
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** 副作用：同步文档语言与本地偏好，兼顾首次加载和后续切换。 */
function persistLanguage(language: string) {
  const resolved = language.startsWith("zh") ? "zh" : "en";
  document.documentElement.lang = resolved === "zh" ? "zh-CN" : "en";
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, resolved);
}

const initialLanguage = resolveInitialLanguage();
persistLanguage(initialLanguage);

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage,
  fallbackLng: "en",
  supportedLngs: ["zh", "en"],
  interpolation: { escapeValue: false },
});

i18n.on("languageChanged", persistLanguage);

export default i18n;
